/* RFC 4231 HMAC-SHA-256 test vectors.
 *
 * The seven canonical cases from RFC 4231 §4.2-§4.8. Each vector pairs a
 * key and a message with the expected 32-byte HMAC-SHA-256 output. Case 5
 * in the RFC also exercises output truncation; we verify the full digest
 * here and leave any truncation logic to the caller. */

#include <stddef.h>
#include <stdint.h>

typedef struct hmacTestVector {
    const char *name;
    const uint8_t *key;
    const uint8_t *data;
    size_t key_len;
    size_t data_len;
    const uint8_t expected[32];
} hmacTestVector;

